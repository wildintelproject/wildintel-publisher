import { useState } from 'react'
import { api } from '../api'
import { TRAIL_ICONS, useTrail } from '../components/Trail'

interface Props { onStart: () => void }

/** What the application does, as the steps of the wizard it opens, in order. */
const STEPS = [
  { title: 'Choose', description: 'What to publish: a Camtrap DP package, an AI dataset in YOLO format or a software application' },
  { title: 'Fetch', description: 'Get it from Trapper, a git repository, a public URL or a folder on this computer' },
  { title: 'Review', description: 'Check the metadata that was found, fill in what is missing and choose any preprocessing' },
  { title: 'Package', description: 'Download the files and build the package that will be published' },
  { title: 'Publish', description: 'Send it to B2SHARE, GBIF, Hugging Face Hub or Zenodo — one or several, in the order you choose' },
]

export default function WelcomePage({ onStart }: Props) {
  useTrail([{ label: 'Home', icon: TRAIL_ICONS.home }], 'Fetch data products and publish them to a range of repositories')
  // the tick that says the page is not shown again: kept in the settings (General), where it is turned on again
  const [hide, setHide] = useState(false)
  const [hideError, setHideError] = useState<string | null>(null)
  async function hideNextTime(hidden: boolean) {
    setHideError(null)
    setHide(hidden)
    try {
      await api.setShowWelcome(!hidden)
    } catch (e) {
      setHide(!hidden)
      setHideError(e instanceof Error ? e.message : 'The setting could not be saved.')
    }
  }
  return (
    <div className="mx-auto max-w-[1100px] px-4 py-10 flex flex-col items-center" style={{ minHeight: 'calc(100vh - 56px)' }}>
      <img src="/logo.svg" alt="" aria-hidden="true" width={64} height={64} className="mb-3 h-16 w-16 rounded-2xl" />
      <h1 className="text-2xl font-bold mb-2 text-center">WildINTEL Publisher</h1>
      <p className="mb-8 max-w-[760px] text-center text-base leading-relaxed text-zinc-500 dark:text-zinc-400">
        Fetch the data products generated by the WildINTEL project, review their metadata and publish them to the{' '}
        <strong className="font-semibold text-zinc-900 dark:text-zinc-100">repositories</strong> that make them findable and citable.
      </p>
      <ol className="grid w-full list-none grid-cols-1 gap-x-8 gap-y-5 p-0 m-0 text-left sm:grid-cols-2 lg:grid-cols-5">
        {STEPS.map((step, i) => (
          <li key={step.title} className="flex items-start gap-3 text-sm text-zinc-500 dark:text-zinc-400">
            <span aria-hidden="true" className="mt-0.5 flex h-6 w-6 shrink-0 items-center justify-center rounded-full border border-zinc-300 dark:border-zinc-600 text-xs font-semibold text-zinc-600 dark:text-zinc-300">
              {i + 1}
            </span>
            <span><strong className="block font-semibold text-zinc-900 dark:text-zinc-100">{step.title}</strong>{step.description}</span>
          </li>
        ))}
      </ol>
      <button
        type="button"
        className="mt-8 px-6 py-2.5 bg-blue-600 text-white rounded-lg hover:bg-blue-700 transition-colors text-base flex items-center gap-2"
        onClick={onStart}
      >
        <svg width="18" height="18" viewBox="0 0 24 24" fill="none" aria-hidden="true">
          <path d="M12 5v14M5 12h14" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" />
        </svg>
        Get Started
      </button>
      {/* a tick, to open the next times on what comes after this page */}
      <label className="mt-6 flex cursor-pointer items-center gap-2 text-sm text-zinc-600 dark:text-zinc-400">
        <input type="checkbox" checked={hide} onChange={(e) => void hideNextTime(e.target.checked)} className="h-4 w-4 rounded border-zinc-400" />
        Do not show this page again
      </label>
      {hideError && <p role="alert" className="mt-1 text-xs text-red-600 dark:text-red-400">{hideError}</p>}
    </div>
  )
}
